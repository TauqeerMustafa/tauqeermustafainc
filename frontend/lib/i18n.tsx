/** English is the source language, so it needs no table of its own. */
const DICTIONARIES: Partial<Record<LocaleCode, Dictionary>> = { ur, ar, fr, es, zh };

export function localeMeta(code: LocaleCode): LocaleMeta {
  return LOCALES.find((entry) => entry.code === code) ?? LOCALES[0];
}

/** `en-GB`, `ur-PK`, `zh-Hans-CN` → the base language we actually have a table
 *  for, or English when we have none. */
function normalize(tag: string | null | undefined): LocaleCode {
  const base = (tag ?? "").toLowerCase().split(/[-_]/)[0];
  return LOCALES.some((entry) => entry.code === base) ? (base as LocaleCode) : "en";
}

export type Translate = (text: string, vars?: Record<string, string | number>) => string;

type I18nValue = {
  locale: LocaleCode;
  setLocale: (locale: LocaleCode) => void;
  t: Translate;
  dir: "ltr" | "rtl";
  locales: LocaleMeta[];
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  // Starts English so the server render and the first client pass agree; the
  // stored/browser locale is applied right after mount.
  const [locale, setLocaleState] = useState<LocaleCode>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    setLocaleState(normalize(stored ?? window.navigator.language));
  }, []);

  const setLocale = useCallback((next: LocaleCode) => {
    setLocaleState(next);
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // Private browsing can refuse writes; the choice just won't outlive the tab.
    }
  }, []);

  const t = useCallback<Translate>(
    (text, vars) => {
      const table = DICTIONARIES[locale];
      let out = table?.[text] ?? text;
      if (vars) {
        for (const [key, value] of Object.entries(vars)) {
          out = out.split(`{${key}}`).join(String(value));
        }
      }
      return out;
    },
    [locale],
  );

  const value = useMemo<I18nValue>(
    () => ({ locale, setLocale, t, dir: localeMeta(locale).dir, locales: LOCALES }),
    [locale, setLocale, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

/**
 * Falls back to an English pass-through rather than throwing, so a component can
 * call `t()` without caring whether a provider happens to be above it.
 */
export function useI18n(): I18nValue {
  const context = useContext(I18nContext);
  if (context) return context;
  return {
    locale: "en",
    setLocale: () => {},
    t: (text) => text,
    dir: "ltr",
    locales: LOCALES,
  };
}
